@Composable
fun XdlTheme(
    dark: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    // 设计稿指定固定 blue 调色板（paletteKey: blue），不跟随壁纸动态取色
    val scheme = if (dark) DarkColors else LightColors
    MaterialTheme(
        colorScheme = scheme,
        typography = XdlTypography,
        shapes = XdlShapes,
        content = content
    )
}
